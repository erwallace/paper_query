# This script evaluates a set of question-answer pairs using the RAG chatbot.
import json

from loguru import logger
from paper_query.chatbots import HybridQueryChatbot
from paper_query.constants import METRICS_JSON, assets_dir
from ragchecker import RAGChecker, RAGResults
from ragchecker.metrics import all_metrics

QNA_BENCHMARKS = "evaluation/qna_benchmarks.json"
INTERMIDATE_RESULTS = "evaluation/qna_benchmarks_answered.json"


def answer_queries(qa: dict) -> dict:
    """Answer test questions in the RAG benchmark using the Chatbot.

    Parameters
    ----------
    qa : dict
        A dictionary containing the benchmark questions and answers.

        {
            "results": [ # A list of QA pairs
                {
                    "query_id": "000",
                    "query": "This is the question for the first example",
                    "gt_answer": "This is the ground truth answer for the first example"
                },
                {
                    "query_id": "001",
                    "query": "This is the question for the second example",
                    "gt_answer": "This is the ground truth answer for the second example"
                },
                ...
            ]
        }

    Returns
    -------
    dict
        A dictionary containing the benchmark questions and answers with responses and retrieved
        contexts.

        {
            "results": [ # A list of QA pairs with responses
                {
                    "query_id": "000",
                    "query": "This is the question for the first example",
                    "gt_answer": "This is the ground truth answer for the first example",
                    "response": "This is the response generated by the chatbot",
                    "retrieved_context": [
                        {"doc_id": "doc1", "text": "Content from document 1"},
                        {"doc_id": "doc2", "text": "Content from document 2"}
                    ]
                },
                ...
            ]
        }

    """
    if not qa or "results" not in qa:
        raise ValueError("Input must contain 'results' key")

    chatbot = HybridQueryChatbot(
        model_name="gpt-4.1",
        model_provider="openai",
        paper_path=str(assets_dir / "strainrelief_preprint.pdf"),
        references_dir=str(assets_dir / "references"),
    )

    for qa_pair in qa["results"]:
        if "query" not in qa_pair.keys() or "gt_answer" not in qa_pair.keys():
            raise ValueError("Each QA pair must contain 'query' and 'gt_answer' keys")

        # Stream the response (consuming all chunks)
        for _ in chatbot.stream_response(qa_pair["query"]):
            pass

        # Extract response and context from chat history
        last_message = chatbot.chat_history[-1]
        qa_pair["response"] = last_message.content
        qa_pair["retrieved_context"] = _extract_context(last_message)

    return qa


def _extract_context(message) -> list[dict]:
    """Extract and format retrieved context from chat message."""
    context_data = message.response_metadata.get("context", [])
    return [
        {"doc_id": context["Document Title"], "text": context["Content"]}
        for context in context_data
        if "Document Title" in context and "Content" in context
    ]


if __name__ == "__main__":
    # Load the RAG benchmark Q&As from a JSON file
    with open(QNA_BENCHMARKS) as f:
        qa = json.load(f)

    # Answer each query using the Chatbot
    qa_answered = answer_queries(qa)

    # Save the updated Q&As with responses and retrieved documents
    with open(INTERMIDATE_RESULTS, "w") as f:
        json.dump(qa_answered, f, indent=4)

    # Initialise RAGResults from the answered Q&As
    rag_results = RAGResults.from_dict(qa_answered)

    # Set up the evaluator
    evaluator = RAGChecker(
        extractor_name="openai/gpt-4.1",
        checker_name="openai/gpt-4.1",
        batch_size_extractor=32,
        batch_size_checker=32,
    )

    # Evaluate results with selected metrics or certain groups
    # e.g., retriever_metrics, generator_metrics, all_metrics
    evaluator.evaluate(rag_results, all_metrics, save_path=METRICS_JSON)

    logger.info(rag_results)
    logger.info(f"Evaluation complete. Metrics saved to {METRICS_JSON}.")
